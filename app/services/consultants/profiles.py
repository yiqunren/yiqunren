@dataclass(frozen=True)
class Profile:
    slug: str
    name: str
    mission: str
    inputs: tuple[str, ...]
    method: tuple[str, ...]
    evidence: tuple[str, ...]
    limits: tuple[str, ...]
    output: tuple[str, ...]
    personality: str
    thinking_preference: str
    version: int = VERSION

    def specification(self):
        return {**asdict(self), "principles": COMMON_PRINCIPLES,
                "permissions": {"tools": False, "execution": False, "external_fetch": False}}

    @property
    def digest(self):
        return hashlib.sha256(json.dumps(self.specification(), ensure_ascii=False,
            sort_keys=True, separators=(",", ":")).encode()).hexdigest()


